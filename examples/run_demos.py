#!/usr/bin/env python3
"""Reproduce the worked demonstrations by running library skill scripts on synthetic inputs.

Each examples/<demo>/demo.json lists steps:
  {"id": "03-req-lint", "skill": "se-requirements", "script": "req_lint.py",
   "args": ["inputs/requirements.csv", "--json"], "expect_exit": 0,
   "output": "outputs/03-req-lint.json", "purpose": "why this step exists"}
Steps run with the demo directory as working directory; stdout is saved to `output`.
A step "passes" when its exit code equals expect_exit (an expected 1 demonstrates a check catching a
seeded or real defect). outputs/RUN-SUMMARY.md records every step.

Usage:
  python3 examples/run_demos.py            # regenerate all outputs
  python3 examples/run_demos.py --check    # re-run and fail if exit codes or outputs drift
  python3 examples/run_demos.py --demo aster
Exit: 0 all steps as expected (and no drift with --check), 1 otherwise.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
SKILLS = ROOT / ".claude" / "skills"


def run_step(demo_dir: Path, step: dict) -> tuple[int, str]:
    script = SKILLS / step["skill"] / "scripts" / step["script"]
    if not script.is_file():
        return 99, f"missing script {script}"
    p = subprocess.run([sys.executable, "-I", str(script), *step["args"]], cwd=demo_dir,
                       capture_output=True, text=True, timeout=300)
    out = p.stdout if p.stdout.strip() else p.stderr
    return p.returncode, out.replace(str(ROOT), "<library>")


def norm(s: str) -> str:
    return "\n".join(line.rstrip() for line in s.strip().splitlines())


def run_demo(demo_dir: Path, check: bool) -> list[dict]:
    spec = json.loads((demo_dir / "demo.json").read_text(encoding="utf-8"))
    results = []
    for step in spec["steps"]:
        code, out = run_step(demo_dir, step)
        target = demo_dir / step["output"]
        drift = False
        if check:
            drift = not target.is_file() or norm(target.read_text(encoding="utf-8")) != norm(out)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(out if out.endswith("\n") else out + "\n", encoding="utf-8")
        results.append({"id": step["id"], "skill": step["skill"], "script": step["script"],
                        "expected": step["expect_exit"], "actual": code, "ok": code == step["expect_exit"],
                        "drift": drift, "output": step["output"], "purpose": step.get("purpose", "")})
    if not check:
        lines = [f"# Run summary — {spec['title']}", "",
                 "_Generated by `python3 examples/run_demos.py`. Exit code 1 where expected means a check found the defect it was meant to find._", "",
                 "| Step | Skill / script | Purpose | Expected exit | Actual | Result | Output |", "|---|---|---|---|---|---|---|"]
        for r in results:
            lines.append(f"| {r['id']} | `{r['skill']}` / `{r['script']}` | {r['purpose']} | {r['expected']} | {r['actual']} | "
                         f"{'as expected' if r['ok'] else '**UNEXPECTED**'} | [{Path(r['output']).name}]({Path(r['output']).name}) |")
        (demo_dir / "outputs" / "RUN-SUMMARY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return results


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--demo")
    a = ap.parse_args(argv)
    demos = sorted(d for d in HERE.iterdir() if (d / "demo.json").is_file() and (not a.demo or d.name == a.demo))
    if not demos:
        print("no demos found", file=sys.stderr)
        return 1
    bad = 0
    for d in demos:
        res = run_demo(d, a.check)
        for r in res:
            flag = "ok" if r["ok"] and not r["drift"] else ("DRIFT" if r["drift"] else "UNEXPECTED EXIT")
            if flag != "ok":
                bad += 1
            print(f"[{flag:<15}] {d.name:<20} {r['id']:<28} exit {r['actual']} (expected {r['expected']})")
    print(f"\n{'PASS' if not bad else 'FAIL'}: {len(demos)} demos, {bad} problems")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
