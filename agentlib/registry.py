"""Build ``registry.json``: a deterministic index of every library component.

The registry is generated, never hand-edited. CI fails when it is stale.
"""
from __future__ import annotations

import json
from pathlib import Path

import yaml

from agentlib import frontmatter
from agentlib.paths import repo_root


def _first_line(text: str) -> str:
    return " ".join(str(text).split())


def build_registry(root: Path | None = None) -> dict:
    root = root or repo_root()
    reg: dict = {"schema_version": 1, "skills": [], "agents": [], "commands": [], "workflows": [], "catalogs": [], "eval_suites": []}
    for md in sorted((root / "skills").glob("*/SKILL.md")):
        meta, _ = frontmatter.load(md)
        m = meta.get("metadata", {})
        reg["skills"].append({
            "name": meta["name"],
            "path": str(md.parent.relative_to(root)),
            "description": _first_line(meta["description"]),
            "category": m.get("category"),
            "version": m.get("version"),
            "maturity": m.get("maturity"),
            "sources": m.get("sources", []),
            "catalogs": m.get("catalogs", []),
            "tools": m.get("tools", []),
            "has_eval_suite": (root / "evals" / meta["name"] / "cases.yaml").is_file(),
        })
    for md in sorted((root / "agents").glob("*.md")):
        meta, _ = frontmatter.load(md)
        reg["agents"].append({
            "name": meta["name"],
            "path": str(md.relative_to(root)),
            "description": _first_line(meta["description"]),
            "model": meta.get("model", "inherit"),
        })
    for md in sorted((root / "commands").glob("*.md")):
        meta, _ = frontmatter.load(md)
        reg["commands"].append({"name": md.stem, "path": str(md.relative_to(root)), "description": _first_line(meta["description"])})
    for wf in sorted((root / "workflows").glob("*.yaml")):
        data = yaml.safe_load(wf.read_text(encoding="utf-8"))
        reg["workflows"].append({
            "id": data["id"],
            "path": str(wf.relative_to(root)),
            "title": data["title"],
            "version": data["version"],
            "stages": [s["id"] for s in data["stages"]],
        })
    for cat in sorted((root / "catalog").glob("*.json")):
        data = json.loads(cat.read_text(encoding="utf-8"))
        reg["catalogs"].append({
            "id": data["catalog_id"],
            "path": str(cat.relative_to(root)),
            "source_id": data["source_id"],
            "edition": data["edition"],
            "items": len(data["items"]),
            "fidelity": data["extraction"]["fidelity"],
        })
    for suite in sorted((root / "evals").glob("*/cases.yaml")):
        data = yaml.safe_load(suite.read_text(encoding="utf-8"))
        reg["eval_suites"].append({"skill": data.get("skill"), "path": str(suite.relative_to(root)), "cases": len(data.get("cases", []))})
    return reg


def write_registry(root: Path | None = None) -> Path:
    root = root or repo_root()
    path = root / "registry.json"
    path.write_text(json.dumps(build_registry(root), indent=2) + "\n", encoding="utf-8")
    (root / "docs").mkdir(exist_ok=True)
    (root / "docs" / "CATALOGUE.md").write_text(build_catalogue(root), encoding="utf-8")
    return path


def build_catalogue(root: Path | None = None) -> str:
    """Human-readable catalogue (docs/CATALOGUE.md) generated from the registry."""
    root = root or repo_root()
    reg = build_registry(root)
    out = ["# Library catalogue", "",
           "_Generated by `python -m agentlib registry --write`; do not edit by hand._", "",
           f"{len(reg['skills'])} skills · {len(reg['agents'])} agents · {len(reg['workflows'])} workflows · "
           f"{len(reg['commands'])} commands · {len(reg['catalogs'])} catalogs "
           f"({sum(c['items'] for c in reg['catalogs'])} items) · "
           f"{sum(s['cases'] for s in reg['eval_suites'])} eval cases", "", "## Skills", ""]
    for sk in reg["skills"]:
        out += [f"### `{sk['name']}` ({sk['category']}, {sk['maturity']}, v{sk['version']})", "", sk["description"], ""]
        if sk["sources"]:
            out.append(f"- Sources: {', '.join(f'`{x}`' for x in sk['sources'])}")
        if sk["catalogs"]:
            out.append(f"- Catalogs: {', '.join(f'`{x}`' for x in sk['catalogs'])}")
        if sk["tools"]:
            out.append(f"- Tools: {', '.join(f'`{x}`' for x in sk['tools'])}")
        out += [f"- Path: [{sk['path']}/SKILL.md](../{sk['path']}/SKILL.md)", ""]
    out += ["## Agents", "", "| Agent | Model | Description |", "|---|---|---|"]
    out += [f"| [`{a['name']}`](../{a['path']}) | {a['model']} | {a['description']} |" for a in reg["agents"]]
    out += ["", "## Workflows", "", "| Workflow | Stages |", "|---|---|"]
    out += [f"| [`{w['id']}`](../{w['path']}) {w['title']} | {' → '.join(w['stages'])} |" for w in reg["workflows"]]
    out += ["", "## Commands", "", "| Command | Description |", "|---|---|"]
    out += [f"| [`/{c['name']}`](../{c['path']}) | {c['description']} |" for c in reg["commands"]]
    out += ["", "## Catalogs", "", "| Catalog | Source | Edition | Items | Fidelity |", "|---|---|---|---|---|"]
    out += [f"| [`{c['id']}`](../{c['path']}) | `{c['source_id']}` | {c['edition']} | {c['items']} | {c['fidelity']} |" for c in reg["catalogs"]]
    return "\n".join(out) + "\n"
