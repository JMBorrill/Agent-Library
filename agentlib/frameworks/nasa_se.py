def _load_any(path: Path):
    text = path.read_text(encoding="utf-8-sig")
    if path.suffix.lower() in (".yaml", ".yml"):
        return yaml.safe_load(text)
    if path.suffix.lower() == ".json":
        return json.loads(text)
    if path.suffix.lower() in (".csv", ".tsv"):
        return list(csv.reader(io.StringIO(text), delimiter="\t" if path.suffix.lower() == ".tsv" else ","))
    raise InputError(f"unsupported file type '{path.suffix}'")


def _trade_from_rows(rows: list[list[str]]) -> dict:
    rows = [r for r in rows if any(c.strip() for c in r)]
    if len(rows) < 3:
        raise InputError("CSV needs a header row, a 'weight' row and at least one alternative row")
    header = [c.strip() for c in rows[0]]
    crit_names = header[1:]
    weights, mandatory, alts = None, {}, []
    for r in rows[1:]:
        label = r[0].strip()
        vals = [c.strip() for c in r[1:]]
        if label.lower() in ("weight", "weights"):
            weights = vals
        elif label.lower() in ("mandatory", "must"):
            mandatory = {c: v.lower() in ("yes", "y", "true", "1", "mandatory") for c, v in zip(crit_names, vals)}
        else:
            alts.append({"name": label, "scores": dict(zip(crit_names, vals))})
    if weights is None:
        raise InputError("CSV needs a row labelled 'weight'")
    criteria = [{"name": c, "weight": w, "mandatory": mandatory.get(c, False)} for c, w in zip(crit_names, weights)]
    return {"criteria": criteria, "alternatives": alts}


def _num(v, what: str) -> float:
    try:
        return float(str(v).strip().rstrip("%"))
    except (TypeError, ValueError) as exc:
        raise InputError(f"{what}: '{v}' is not a number") from exc


def trade_study(spec: dict, close_margin: float = 0.05) -> dict:
    """Weighted-sum decision matrix (6.8.1.2). Mandatory criteria are pass/fail screens (6.8.1.2.1)."""
    if not isinstance(spec, dict) or not spec.get("criteria") or not spec.get("alternatives"):
        raise InputError("trade study needs 'criteria' and 'alternatives'")
    crits = spec["criteria"]
    scored = [c for c in crits if not c.get("mandatory")]
    mandatory = [c["name"] for c in crits if c.get("mandatory")]
    if not scored:
        raise InputError("at least one non-mandatory (weighted) criterion is required")
    raw_w = {c["name"]: _num(c.get("weight"), f"weight of '{c['name']}'") for c in scored}
    if any(w < 0 for w in raw_w.values()):
        raise InputError("weights must be non-negative")
    total_w = sum(raw_w.values())
    if total_w <= 0:
        raise InputError("weights sum to zero")
    weights = {k: v / total_w for k, v in raw_w.items()}
    notes = []
    if abs(total_w - 1) > 1e-6 and abs(total_w - 100) > 1e-6:
        notes.append(f"Weights summed to {total_w:g}; normalised to 1.0.")
    results, disregarded = [], []
    for alt in spec["alternatives"]:
        name = alt.get("name") or "(unnamed)"
        scores = alt.get("scores") or {}
        failed = []
        for m in mandatory:
            v = scores.get(m, alt.get("meets", {}).get(m) if isinstance(alt.get("meets"), dict) else None)
            ok = v if isinstance(v, bool) else str(v).strip().lower() in ("yes", "y", "true", "pass", "1", "met")
            if not ok:
                failed.append(m)
        missing = [c for c in weights if c not in scores or str(scores[c]).strip() == ""]
        if missing:
            raise InputError(f"alternative '{name}' has no score for: {', '.join(missing)}")
        contrib = {c: round(weights[c] * _num(scores[c], f"score {name}/{c}"), 6) for c in weights}
        total = round(sum(contrib.values()), 6)
        entry = {"name": name, "weighted_total": total, "scores": {c: _num(scores[c], c) for c in weights},
                 "contributions": contrib, "failed_mandatory": failed}
        (disregarded if failed else results).append(entry)
    results.sort(key=lambda e: e["weighted_total"], reverse=True)
    for rank, e in enumerate(results, start=1):
        e["rank"] = rank
    close = False
    if len(results) >= 2:
        top, second = results[0]["weighted_total"], results[1]["weighted_total"]
        if top == 0 or (top - second) / abs(top) <= close_margin:
            close = True
            notes.append(f"Top alternatives are within {close_margin:.0%}: present all closely ranked alternatives "
                         "to the decision-maker and assess whether uncertainty could change the ranking (6.8.1.2.5).")
    if disregarded:
        notes.append("Alternatives failing a mandatory criterion are disregarded (6.8.1.2.1).")
    return {"source": f"{SOURCE} 6.8 Decision Analysis", "weights": {k: round(v, 6) for k, v in weights.items()},
            "mandatory_criteria": mandatory, "ranking": results, "disregarded": disregarded,
            "closely_ranked": close, "recommended": results[0]["name"] if results and not close else None,
            "notes": notes}


def render_trade(res: dict, fmt: str) -> str:
    if fmt == "json":
        return json.dumps(res, indent=2, ensure_ascii=False)
    crits = list(res["weights"])
    L = ["# Decision matrix (weighted sum)", "", f"Source: {res['source']}", "",
         "| Criterion | Weight | " + " | ".join(e["name"] for e in res["ranking"]) + " |",
         "|---|---|" + "---|" * len(res["ranking"])]
    for c in crits:
        L.append(f"| {c} | {res['weights'][c]:.3f} | " +
                 " | ".join(f"{e['scores'][c]:g}" for e in res["ranking"]) + " |")
    L.append("| **Weighted total** | 1.000 | " + " | ".join(f"**{e['weighted_total']:.3f}**" for e in res["ranking"])
             + " |")
    L += ["", "Cells are raw scores; weighted total = sum(normalised weight x score).", ""]
    L += [f"{e['rank']}. {e['name']}: {e['weighted_total']:.3f}" for e in res["ranking"]]
    if res["mandatory_criteria"]:
        L += ["", "Mandatory criteria: " + ", ".join(res["mandatory_criteria"])]
    for e in res["disregarded"]:
        L.append(f"- Disregarded: {e['name']} (fails {', '.join(e['failed_mandatory'])})")
    if res["notes"]:
        L += [""] + [f"- {n}" for n in res["notes"]]
    if res["recommended"]:
        L += ["", f"Highest score: {res['recommended']} (document rationale, assumptions, uncertainty and any dissent; "
                  "Table 6.8-1)."]
    return "\n".join(L) + "\n"


