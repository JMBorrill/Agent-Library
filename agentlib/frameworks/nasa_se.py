def parse_methods(value: str) -> tuple[list[str], list[str]]:
    """Split a verification-method cell into (valid canonical methods, invalid tokens)."""
    valid, invalid = [], []
    s = (value or "").strip()
    if not s:
        return valid, invalid
    tokens = [t.strip() for t in re.split(r"[,;/&+]|\band\b|\s{2,}", s, flags=re.I) if t.strip()]
    if len(tokens) == 1 and re.fullmatch(r"[TAIDtaid]{2,4}", tokens[0]):
        tokens = list(tokens[0])  # e.g. "TA" -> T, A
    for tok in tokens:
        key = re.sub(r"[^a-z]", "", tok.lower())
        canon = METHOD_SYNONYMS.get(key)
        if canon:
            if canon not in valid:
                valid.append(canon)
        else:
            invalid.append(tok)
    return valid, invalid


def _term_regex(term: str) -> re.Pattern:
    esc = re.escape(term)
    lead = r"(?<![\w/])" if term[0].isalnum() else ""
    trail = r"(?![\w/-])" if term[-1].isalnum() else ""
    return re.compile(lead + esc + trail, re.I)


@lru_cache(maxsize=None)
def _term_sets() -> tuple:
    p = catalog(CHECKLIST_ID)["parameters"]
    unver = sorted(set(p["unverifiable_terms"]), key=len, reverse=True)
    amb = p["ambiguous_terms"]
    pron = p["indefinite_pronouns"]
    return ([(t, _term_regex(t)) for t in unver], [(t, _term_regex(t)) for t in amb],
            [(t, _term_regex(t)) for t in pron])


def _source_for(rule: str) -> str:
    item = checklist_item(RULES[rule][1])
    sec = item["citation"].get("section", "")
    label = item.get("title") or item["id"]
    return f"{SOURCE} {sec} ({label}) {cite(item)}"


def _f(req: Requirement, rule: str, message: str, evidence: str = "") -> Finding:
    return Finding(req.id or f"(line {req.line})", rule, RULES[rule][0], message, evidence, _source_for(rule), req.line)


def lint_requirement(req: Requirement, require_rationale: bool = True,
                     require_verification: bool = True) -> list[Finding]:
    out: list[Finding] = []
    text = re.sub(r"\s+", " ", req.text or "").strip()
    if not req.id:
        out.append(_f(req, "missing-id", "Requirement has no unique identifier (Table 4.2-2 'Requirement ID')."))
    if not text:
        out.append(_f(req, "empty-text", "Requirement statement is empty."))
        return out
    low = text.lower()
    shalls = re.findall(r"\bshall\b", low)
    if not shalls:
        alt = re.search(r"\b(will|should|must|may|shall\w+)\b", low)
        if alt and alt.group(1) == "will":
            msg = "No 'shall': 'will' states a fact or declaration of purpose, not a requirement (C.1)."
        elif alt and alt.group(1) == "should":
            msg = "No 'shall': 'should' states a goal, not a requirement (C.1)."
        elif alt and alt.group(1) == "must":
            msg = "No 'shall': the handbook uses 'shall' for requirements (C.1); 'must' is not a defined term."
        else:
            msg = "Statement contains no 'shall'; requirements are written as 'shall' statements (C.1, 4.2.1.2.3)."
        out.append(_f(req, "no-shall", msg, alt.group(0) if alt else ""))
    elif len(shalls) > 1:
        out.append(_f(req, "multiple-shall", f"{len(shalls)} 'shall' in one statement; use a single 'shall' per "
                                             "requirement (4.2.1.2.3) and one thought per statement (C.4).",
                      f"{len(shalls)} x shall"))
    unver, amb, pron = _term_sets()
    amb_hits = [t for t, rx in amb if rx.search(text)]
    for t in amb_hits:
        out.append(_f(req, "ambiguous-term", f"Ambiguous term '{t}' (C.4 Clarity).", t))
    masked = TERM_EXCEPTIONS.sub(" ", text)
    for t, rx in amb:
        masked = rx.sub(" ", masked)
    seen = set()
    for t, rx in unver:
        m = rx.search(masked)
        if m and t not in seen:
            seen.add(t)
            masked = rx.sub(" ", masked)
            out.append(_f(req, "unverifiable-term", f"Unverifiable term '{t}' (C.4 Verifiability/Testability); "
                                                    "replace with a measurable criterion.", m.group(0)))
    for m in re.finditer(r"\b([A-Za-z]{3,}ly)\b", masked):
        w = m.group(1).lower()
        if w not in LY_STOP:
            out.append(_f(req, "ly-ize-word", f"'-ly' word '{m.group(1)}' is often unverifiable (C.4).", m.group(1)))
    for m in re.finditer(r"\b([A-Za-z]{2,}iz(?:e|es|ed|ing))\b", masked):
        stem = re.sub(r"(?:es|ed|ing|e)$", "", m.group(1).lower()) + "e"
        if stem not in IZE_STOP:
            out.append(_f(req, "ly-ize-word", f"'-ize' word '{m.group(1)}' is often unverifiable (C.4).", m.group(1)))
    for t, rx in pron:
        m = rx.search(text)
        if m and not re.match(rf"\s*{t}\s+(?:requirement|document|specification|section)", text[m.start():], re.I):
            out.append(_f(req, "indefinite-pronoun", f"Indefinite pronoun '{t}' may be ambiguous (C.4 Clarity).", t))
    for m in re.finditer(r"\bTBD\b|\bTo Be Determined\b", text, re.I):
        out.append(_f(req, "tbd", "TBD value: minimise TBDs; use a best estimate marked TBR with rationale, owner "
                                  "and closure date (C.3).", m.group(0)))
        break
    if re.search(r"\bTBR\b|\bTo Be Resolved\b", text, re.I):
        out.append(_f(req, "tbr", "TBR present: track its rationale, the action to resolve it, who is responsible "
                                  "and by when (C.3).", "TBR"))
    if re.search(r"\bshall\s+not\b", low):
        out.append(_f(req, "negative-statement", "Stated negatively ('shall not'); state requirements positively "
                                                 "where possible (C.3).", "shall not"))
    pm = re.search(r"\bshall\s+(?:not\s+)?be\s+([a-z]+(?:ed|en))\b", low)
    if pm and pm.group(1) not in {"located", "oriented", "rated", "sized", "based", "open", "given", "even"}:
        out.append(_f(req, "passive-voice", "Passive voice; use the active form 'The <product/party> shall <verb>' "
                                            "(C.2).", pm.group(0)))
    if re.search(rf"^\s*(?:the\s+|each\s+|all\s+)?{OPERATOR_SUBJECTS}\s+shall\b", low):
        out.append(_f(req, "operational-statement", "Subject is an operator/user: likely an operational statement; "
                                                    "move to the ConOps or restate as a product requirement (C.2, "
                                                    "C.4 Compliance).", text.split(" shall")[0]))
    after = low.split("shall", 1)[1] if "shall" in low else ""
    if len(shalls) <= 1 and after and (";" in after or re.search(r",?\s+and\s+(?:shall\s+)?(?:also\s+)?"
                                                                    r"(?:provide|perform|transmit|store|record|"
                                                                    r"display|generate|support|operate|maintain|"
                                                                    r"monitor|report|detect|send|receive|log|"
                                                                    r"withstand|measure|notify|allow)\b", after)):
        out.append(_f(req, "compound-statement", "Possible compound requirement (more than one predicate); split so "
                                                 "each statement has one subject and one predicate (C.4).",
                      after.strip()[:60]))
    sentences = [s for s in re.split(r"(?<=[.!?])\s+(?=[A-Z])", text) if s.strip()]
    if len(sentences) > 1:
        out.append(_f(req, "multiple-sentences", "More than one sentence: keep rationale and additional thoughts out "
                                                 "of the requirement statement (C.4 Clarity).", sentences[1][:60]))
    if require_rationale and not req.rationale.strip():
        out.append(_f(req, "missing-rationale", "No rationale recorded (C.3; Table 4.2-2 'Rationale')."))
    if req.verification.strip():
        valid, invalid = parse_methods(req.verification)
        for tok in invalid:
            hint = (" Modeling/simulation/similarity are forms of Analysis per the handbook."
                    if re.sub(r"[^a-z]", "", tok.lower()) in ANALYSIS_HINTS else "")
            out.append(_f(req, "invalid-verification-method",
                          f"'{tok}' is not a verification method; use Test, Analysis, Inspection or Demonstration "
                          f"(5.3 Methods of Verification).{hint}", tok))
    elif require_verification:
        out.append(_f(req, "missing-verification-method", "No verification method (Table 4.2-2: determine it as the "
                                                          "requirement is developed)."))
    scrub = STANDARD_REF_RE.sub(" ", text)
    if (req.id or ""):
        scrub = scrub.replace(req.id, " ")
    if QTY_RE.search(scrub) and not any(b in low for b in BOUND_WORDS):
        out.append(_f(req, "missing-tolerance", "Quantity without a tolerance or bound (e.g., less than, greater than "
                                                "or equal to, plus or minus) (C.2).", QTY_RE.search(scrub).group(0)))
    return out


def lint_requirements(reqs: list[Requirement], require_rationale: bool = True,
                      require_verification: bool = True) -> list[Finding]:
    findings: list[Finding] = []
    counts: dict[str, int] = {}
    for r in reqs:
        if r.id:
            counts[r.id] = counts.get(r.id, 0) + 1
    reported = set()
    for r in reqs:
        if r.id and counts[r.id] > 1 and r.id not in reported:
            reported.add(r.id)
            findings.append(_f(r, "duplicate-id", f"Identifier '{r.id}' is used {counts[r.id]} times; each "
                                                  "requirement must be uniquely referenceable (C.4 Traceability).",
                               r.id))
        findings += lint_requirement(r, require_rationale, require_verification)
    return findings


def summarise(findings: list[Finding], n_reqs: int) -> dict:
    by_sev = {s: 0 for s in ("error", "warning", "info")}
    by_rule: dict[str, int] = {}
    for f in findings:
        by_sev[f.severity] += 1
        by_rule[f.rule] = by_rule.get(f.rule, 0) + 1
    bad = {f.req_id for f in findings if f.severity == "error"}
    return {"requirements": n_reqs, "errors": by_sev["error"], "warnings": by_sev["warning"], "info": by_sev["info"],
            "requirements_with_errors": len(bad), "by_rule": dict(sorted(by_rule.items()))}


def _md_escape(s: str) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def render_findings(findings: list[Finding], summary: dict, fmt: str) -> str:
    if fmt == "json":
        return json.dumps({"source": SOURCE, "summary": summary, "findings": [asdict(f) for f in findings]},
                          indent=2, ensure_ascii=False)
    if fmt == "markdown":
        lines = [f"# Requirements lint report ({SOURCE} Appendix C)", "",
                 f"Requirements: {summary['requirements']} | errors: {summary['errors']} | "
                 f"warnings: {summary['warnings']} | info: {summary['info']}", ""]
        if findings:
            lines += ["| Req ID | Severity | Rule | Finding | Evidence | Source |", "|---|---|---|---|---|---|"]
            for f in findings:
                lines.append(f"| {_md_escape(f.req_id)} | {f.severity} | {f.rule} | {_md_escape(f.message)} | "
                             f"{_md_escape(f.evidence)} | {_md_escape(f.source)} |")
        else:
            lines.append("No findings.")
        return "\n".join(lines) + "\n"
    rows = [(f.req_id, f.severity.upper(), f.rule, f.message) for f in findings]
    w1 = max([len(r[0]) for r in rows] + [6])
    w3 = max([len(r[2]) for r in rows] + [4])
