    out.append("")
    out.append(f"{summary['requirements']} requirement(s): {summary['errors']} error(s), {summary['warnings']} "
               f"warning(s), {summary['info']} info. Rules: {SOURCE} Appendix C, Table 4.2-2, 5.3.")
    return "\n".join(out) + "\n"


