class InputError(ValueError):
    """Raised for unreadable or structurally invalid input files."""


# --------------------------------------------------------------------------- catalogs
@lru_cache(maxsize=None)
def catalog(name: str) -> dict:
    return load_catalog(name)


def _items(name: str, **filters) -> list[dict]:
    out = []
    for item in catalog(name)["items"]:
        if all(item.get(k) == v for k, v in filters.items()):
            out.append(item)
    return out


def checklist_item(item_id: str) -> dict:
    for item in catalog(CHECKLIST_ID)["items"]:
        if item["id"] == item_id:
            return item
    raise KeyError(item_id)


def cite(item_or_citation: dict, locator: str | None = None) -> str:
    """Library citation syntax: ``[nasa-se <locator>, p. <pdf_page>]``."""
    c = item_or_citation.get("citation", item_or_citation)
    loc = locator or c.get("section", "")
    return f"[nasa-se {loc}, p. {c['pdf_page']}]".replace("nasa-se , p.", "nasa-se, p.")


# --------------------------------------------------------------------------- requirement model
@dataclass
class Requirement:
    id: str | None
    text: str
    rationale: str = ""
    verification: str = ""
    parents: list[str] = field(default_factory=list)
    children: list[str] = field(default_factory=list)
    level: str = ""
    status: str = ""
    line: int = 0


FIELD_ALIASES = {
    "id": {"id", "req id", "requirement id", "req no", "requirement no", "req", "number", "identifier", "key",
           "req number", "requirement number", "unique identifier"},
    "text": {"text", "requirement", "statement", "shall statement", "requirement text", "description",
             "requirement statement"},
    "rationale": {"rationale", "reason", "justification"},
    "verification": {"verification", "verification method", "method", "vm", "verification methods", "methods",
                     "v method"},
    "parents": {"parent", "parents", "traced from", "trace", "traces to", "parent id", "parent ids", "source",
                "parent requirement", "parent requirements", "trace from", "derived from"},
    "children": {"children", "child", "allocated to", "child ids", "child requirements"},
    "level": {"level", "tier", "verification level"},
    "status": {"status", "verification status", "result", "results", "compliance"},
}


def _norm_header(h: str) -> str:
    h = re.sub(r"[_\-]+", " ", str(h).strip().lower())
    h = re.sub(r"[?.:*]+", "", h)
    return re.sub(r"\s+", " ", h).strip()


def _field_for(header: str) -> str | None:
    h = _norm_header(header)
    for fld, names in FIELD_ALIASES.items():
        if h in names:
            return fld
    return None


def _split_ids(value) -> list[str]:
    if value is None:
        return []
    if isinstance(value, (list, tuple)):
        out = []
        for v in value:
            out += _split_ids(v)
        return out
    s = str(value).strip()
    if not s or s.lower() in {"-", "n/a", "na", "none", "—", "–"}:
        return []
    return [t for t in re.split(r"[,;\s]+", s) if t]


def _req_from_mapping(row: dict, line: int) -> Requirement | None:
    data: dict = {}
    for k, v in row.items():
        if k is None:
            continue
        fld = _field_for(k)
        if fld and fld not in data:
            data[fld] = v
    text = str(data.get("text") or "").strip()
    rid = str(data.get("id") or "").strip() or None
    if not text and not rid:
        return None
    ver = data.get("verification") or ""
    if isinstance(ver, (list, tuple)):
        ver = ", ".join(str(v) for v in ver)
    return Requirement(
        id=rid, text=text, rationale=str(data.get("rationale") or "").strip(), verification=str(ver).strip(),
        parents=_split_ids(data.get("parents")), children=_split_ids(data.get("children")),
        level=str(data.get("level") or "").strip(), status=str(data.get("status") or "").strip(), line=line)


def parse_csv(text: str, delimiter: str | None = None) -> list[Requirement]:
    sample = text[:4096]
    if delimiter is None:
        delimiter = "\t" if sample.count("\t") > sample.count(",") else ","
    reader = csv.DictReader(io.StringIO(text), delimiter=delimiter)
    if not reader.fieldnames or not any(_field_for(h) in ("id", "text") for h in reader.fieldnames):
        raise InputError("CSV needs a header row with at least an 'id' or 'text'/'requirement' column")
    reqs = []
    for n, row in enumerate(reader, start=2):
        r = _req_from_mapping(row, n)
        if r:
            reqs.append(r)
    return reqs


def parse_structured(data) -> list[Requirement]:
    if isinstance(data, dict):
        for key in ("requirements", "items", "reqs"):
            if isinstance(data.get(key), list):
                data = data[key]
                break
        else:
            # mapping of id -> text or id -> {fields}
            rows = []
            for k, v in data.items():
                rows.append({"id": k, **v} if isinstance(v, dict) else {"id": k, "text": v})
            data = rows
    if not isinstance(data, list):
        raise InputError("expected a list of requirements (or a mapping with a 'requirements' list)")
    reqs = []
    for n, row in enumerate(data, start=1):
        if isinstance(row, str):
            reqs.append(Requirement(id=None, text=row, line=n))
            continue
        if not isinstance(row, dict):
            raise InputError(f"entry {n} is not a mapping")
        r = _req_from_mapping(row, n)
        if r:
            reqs.append(r)
    return reqs


TABLE_SEP_RE = re.compile(r"^\s*\|?\s*:?-{2,}:?\s*(\|\s*:?-{2,}:?\s*)*\|?\s*$")
ID_TOKEN = r"[A-Za-z][A-Za-z0-9]*(?:[-_.][A-Za-z0-9]+)*-?\d+[A-Za-z0-9.\-]*"
LIST_REQ_RE = re.compile(
    rf"^\s*(?:[-*+]|\d+[.)])?\s*(?:\*\*|`)?\[?(?P<id>{ID_TOKEN})\]?(?:\*\*|`)?\s*[:|\u2013\u2014-]\s+(?P<text>\S.*)$")
HEADING_REQ_RE = re.compile(rf"^#{{2,6}}\s+(?P<id>{ID_TOKEN})\s*[:\u2013\u2014-]?\s*(?P<text>.*)$")
SUBFIELD_RE = re.compile(r"^\s*(?:[-*+]\s*)?(?:\*\*|_)?(?P<key>[A-Za-z][A-Za-z /]+?)(?:\*\*|_)?\s*:\s*(?P<val>.*)$")


def _cells(line: str) -> list[str]:
    s = line.strip()
    if s.startswith("|"):
        s = s[1:]
    if s.endswith("|"):
        s = s[:-1]
    return [c.strip() for c in s.split("|")]


def markdown_tables(text: str) -> list[tuple[list[str], list[tuple[int, list[str]]]]]:
    """Return [(header_cells, [(line_no, row_cells), ...]), ...] for every pipe table."""
    lines = text.splitlines()
    tables, i = [], 0
    while i < len(lines) - 1:
        if "|" in lines[i] and TABLE_SEP_RE.match(lines[i + 1]):
            header = _cells(lines[i])
            rows, j = [], i + 2
            while j < len(lines) and "|" in lines[j] and lines[j].strip():
                rows.append((j + 1, _cells(lines[j])))
                j += 1
            tables.append((header, rows))
            i = j
        else:
            i += 1
    return tables


def _strip_md(s: str) -> str:
    s = re.sub(r"`([^`]*)`", r"\1", s)
    s = re.sub(r"\*\*([^*]*)\*\*", r"\1", s)
    s = re.sub(r"(?<!\w)_([^_]+)_(?!\w)", r"\1", s)
    return s.replace("<br>", " ").strip()


def parse_markdown(text: str) -> list[Requirement]:
    reqs: list[Requirement] = []
    for header, rows in markdown_tables(text):
        fields = [_field_for(_strip_md(h)) for h in header]
        if "text" not in fields and "id" not in fields:
            continue
        if "text" not in fields and not any(f in fields for f in ("parents", "verification")):
            continue
        for line_no, cells in rows:
            row = {header[k]: _strip_md(cells[k]) for k in range(min(len(header), len(cells)))}
            r = _req_from_mapping({_strip_md(k): v for k, v in row.items()}, line_no)
            if r:
                reqs.append(r)
    if reqs:
        return reqs
    current: Requirement | None = None
    in_code = False
    for n, raw in enumerate(text.splitlines(), start=1):
        if raw.strip().startswith("```"):
            in_code = not in_code
            continue
        if in_code or not raw.strip():
            continue
        line = _strip_md(raw)
        m = HEADING_REQ_RE.match(raw.strip()) or LIST_REQ_RE.match(line)
        if m and (not raw.startswith((" ", "\t")) or current is None):
            key = m.group("id")
            if _field_for(key) is None:
                current = Requirement(id=key, text=_strip_md(m.group("text")), line=n)
                reqs.append(current)
                continue
        sm = SUBFIELD_RE.match(line)
        if current is not None and sm:
            fld = _field_for(sm.group("key"))
            if fld == "text" and not current.text:
                current.text = sm.group("val").strip()
                continue
            if fld in ("parents", "children"):
                setattr(current, fld, _split_ids(sm.group("val")))
                continue
            if fld in ("rationale", "verification", "level", "status"):
                setattr(current, fld, sm.group("val").strip())
                continue
        if current is not None and current.text == "" and raw.startswith((" ", "\t")):
            current.text = line
            continue
        if re.search(r"\bshall\b", line, re.I) and not raw.lstrip().startswith("#"):
            current = Requirement(id=None, text=re.sub(r"^\s*(?:[-*+]|\d+[.)])\s+", "", line), line=n)
            reqs.append(current)
    return reqs


def load_requirements(path: str | Path) -> list[Requirement]:
    p = Path(path)
    if not p.is_file():
        raise InputError(f"file not found: {p}")
    text = p.read_text(encoding="utf-8-sig")
    suffix = p.suffix.lower()
    try:
        if suffix in (".csv", ".tsv"):
            reqs = parse_csv(text, "\t" if suffix == ".tsv" else None)
        elif suffix in (".yaml", ".yml"):
            reqs = parse_structured(yaml.safe_load(text))
        elif suffix == ".json":
            reqs = parse_structured(json.loads(text))
        elif suffix in (".md", ".markdown", ".txt"):
            reqs = parse_markdown(text)
        else:
            raise InputError(f"unsupported file type '{suffix}' (use .csv, .tsv, .yaml, .yml, .json or .md)")
    except (yaml.YAMLError, json.JSONDecodeError, csv.Error) as exc:
        raise InputError(f"cannot parse {p.name}: {exc}") from exc
    if not reqs:
        raise InputError(f"no requirements found in {p.name}")
    return reqs


