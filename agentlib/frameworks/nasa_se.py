def _reqs_from_output(output: str) -> list[Requirement]:
    reqs = parse_markdown(output)
    return [r for r in reqs if r.text]


def grade_requirements_quality(output: str, check: dict) -> tuple[bool, str]:
    """Lint the requirements written in ``output`` (Markdown table or list).

    check keys: ``min_requirements`` (default 1), ``max_errors`` (0), ``require_rationale`` (False),
    ``require_verification`` (False), ``require_ids`` (True), ``fail_on_warnings`` (list of rule ids
    treated as errors).
    """
    reqs = _reqs_from_output(output)
    need = int(check.get("min_requirements", 1))
    if len(reqs) < need:
        return False, f"found {len(reqs)} requirement statement(s), need {need}"
    findings = lint_requirements(reqs, bool(check.get("require_rationale", False)),
                                 bool(check.get("require_verification", False)))
    escalate = set(check.get("fail_on_warnings", []))
    if not check.get("require_ids", True):
        findings = [f for f in findings if f.rule != "missing-id"]
    errors = [f for f in findings if f.severity == "error" or f.rule in escalate]
    if check.get("require_rationale"):
        errors += [f for f in findings if f.rule == "missing-rationale"]
    if check.get("require_verification"):
        errors += [f for f in findings if f.rule == "missing-verification-method"]
    max_err = int(check.get("max_errors", 0))
    detail = f"{len(reqs)} requirement(s), {len(errors)} blocking finding(s)"
    if errors:
        detail += ": " + "; ".join(f"{f.req_id} {f.rule} ({f.evidence or f.message[:40]})" for f in errors[:6])
    return len(errors) <= max_err, detail


def _table_with(output: str, *wanted: str) -> list[tuple[list[str], list[tuple[int, list[str]]]]]:
    out = []
    for header, rows in markdown_tables(output):
        low = [_strip_md(h).lower() for h in header]
        if all(any(w in h for h in low) for w in wanted):
            out.append((header, rows))
    return out


def grade_verification_methods(output: str, check: dict) -> tuple[bool, str]:
    """Every row of a verification matrix uses only Test/Analysis/Inspection/Demonstration.

    check keys: ``min_rows`` (default 1), ``column`` (header substring, default "method").
    """
    col = check.get("column", "method").lower()
    tables = _table_with(output, col)
    if not tables:
        return False, f"no Markdown table with a '{col}' column"
    rows_checked, bad = 0, []
    for header, rows in tables:
        idx = next(i for i, h in enumerate(header) if col in _strip_md(h).lower())
        for _, cells in rows:
            if idx >= len(cells):
                continue
            val = _strip_md(cells[idx])
            rows_checked += 1
            valid, invalid = parse_methods(val)
            if invalid or not valid:
                bad.append(val or "(empty)")
    need = int(check.get("min_rows", 1))
    if rows_checked < need:
        return False, f"{rows_checked} row(s) checked, need {need}"
    return not bad, f"{rows_checked} row(s); invalid methods: {bad}" if bad else f"{rows_checked} row(s) all valid"


def grade_trace(output: str, check: dict) -> tuple[bool, str]:
    """Parse a traceability matrix table from ``output`` and require zero trace errors.

    check keys: ``top_levels`` (list), ``external_prefixes`` (list), ``min_requirements`` (1),
    ``require_verification`` (True).
    """
    reqs = [r for r in parse_markdown(output) if r.id]
    need = int(check.get("min_requirements", 1))
    if len(reqs) < need:
        return False, f"found {len(reqs)} traced requirement(s), need {need}"
    rep = trace(reqs, check.get("top_levels"), check.get("external_prefixes"),
                bool(check.get("require_verification", True)))
    errs = [f for f in rep["findings"] if f["severity"] == "error"]
    detail = f"{len(reqs)} requirement(s); {len(errs)} trace error(s)"
    if errs:
        detail += ": " + "; ".join(f"{e['req_id']} {e['check']}" for e in errs[:6])
    return not errs, detail


PHASE_PATTERNS = {
    "pre-phase-a": r"pre-?\s?phase\s+a\b", "phase-a": r"(?<!pre-)(?<!pre )phase\s+a\b", "phase-b": r"phase\s+b\b",
    "phase-c": r"phase\s+c\b", "phase-d": r"phase\s+d\b", "phase-e": r"phase\s+e\b", "phase-f": r"phase\s+f\b",
}


def grade_review_phase_consistency(output: str, check: dict) -> tuple[bool, str]:
    """Lines/table rows naming exactly one life-cycle review must not place it in the wrong phase.

    check keys: ``min_reviews`` (default 1): distinct reviews that must be mentioned with a phase.
    """
    reviews = _items(LIFECYCLE_ID, kind="review")
    names = {}
    for r in reviews:
        for n in [r["acronym"].split("/")[0], *r.get("aliases", [])]:
            if "/" not in n and " " not in n:
                names[n.upper()] = r
        if "/" in r["acronym"]:
            names[r["acronym"].upper()] = r
    rx = re.compile(r"\b(" + "|".join(sorted((re.escape(k) for k in names), key=len, reverse=True)) + r")\b")
    mentioned, wrong = set(), []
    for line in output.splitlines():
        hits = {names[m.group(1).upper()]["id"] for m in rx.finditer(line)}
        if len(hits) != 1:
            continue
        rid = hits.pop()
        rv = next(r for r in reviews if r["id"] == rid)
        low = line.lower()
        phases = {pid for pid, pat in PHASE_PATTERNS.items() if re.search(pat, low)}
        if "pre-phase-a" in phases and not re.search(r"(?<!pre-)(?<!pre )\bphase\s+a\b", low.replace("pre-phase a", "")):
            phases.discard("phase-a")
        if len(phases) != 1:
            continue
        mentioned.add(rid)
        ph = phases.pop()
        if ph not in rv["phases"]:
            wrong.append(f"{rv['acronym']} placed in {ph} (handbook: {', '.join(rv['phases'])})")
    need = int(check.get("min_reviews", 1))
    if wrong:
        return False, "; ".join(wrong)
    if len(mentioned) < need:
        return False, f"{len(mentioned)} review(s) tied to a phase, need {need}"
    return True, f"{len(mentioned)} review/phase pairing(s) consistent"


PROCESS_VARIANTS = {"stakeholder-expectations-definition": r"stakeholder[s]?\s+expectations?\s+definition",
                    "decision-analysis": r"decision\s+analys[ie]s"}


def grade_process_coverage(output: str, check: dict) -> tuple[bool, str]:
    """Count the 17 SE engine process names in ``output`` and reject a wrong process count claim.

    check keys: ``min`` (default 17).
    """
    low = output.lower()
    found = []
    for p in catalog(PROCESSES_ID)["items"]:
        pat = PROCESS_VARIANTS.get(p["id"], re.escape(p["title"].lower()).replace(r"\ ", r"\s+"))
        if re.search(pat, low):
            found.append(p["number"])
    wrong = [int(m.group(1)) for m in re.finditer(r"\b(\d{1,2})\s+(?:common\s+)?(?:technical\s+|se\s+)?processes\b",
                                                   low) if int(m.group(1)) not in (17, 4, 5, 8, 9, 1)]
    need = int(check.get("min", 17))
    missing = [p["title"] for p in catalog(PROCESSES_ID)["items"] if p["number"] not in found]
    if wrong:
        return False, f"claims {wrong} processes; the SE engine has 17 common technical processes"
    return len(found) >= need, f"{len(found)}/17 processes named; missing: {missing}" if missing else "all 17 named"


def _to_float(s: str) -> float | None:
    s = _strip_md(s).replace(",", "").strip().rstrip("%")
    try:
        return float(s)
    except ValueError:
        return None


def grade_decision_matrix(output: str, check: dict) -> tuple[bool, str]:
    """Recompute a weighted decision matrix from the output's table.

    Expects a table whose header has a 'Weight' column followed by one column per alternative, criterion
    rows with numeric weight and raw scores, and a row labelled 'weighted total' (or 'total score').
    Weights must sum to 1 or 100 (``tolerance`` default 0.02 relative); stated totals must equal
    sum(weight x score) (normalised weights) within ``tolerance``.
    """
    tol = float(check.get("tolerance", 0.02))
    for header, rows in _table_with(output, "weight"):
        hl = [_strip_md(h).lower() for h in header]
        wi = next(i for i, h in enumerate(hl) if "weight" in h)
        alt_cols = list(range(wi + 1, len(header)))
        if not alt_cols:
            continue
        weights, scores, totals = [], {c: [] for c in alt_cols}, None
        for _, cells in rows:
            label = _strip_md(cells[0]).lower() if cells else ""
            if "total" in label:
                totals = {c: _to_float(cells[c]) if c < len(cells) else None for c in alt_cols}
                continue
            w = _to_float(cells[wi]) if wi < len(cells) else None
            if w is None:
                continue
            weights.append(w)
            for c in alt_cols:
                scores[c].append(_to_float(cells[c]) if c < len(cells) else None)
        if not weights or totals is None:
            continue
        wsum = sum(weights)
        if not (abs(wsum - 1) <= tol or abs(wsum - 100) <= 100 * tol):
            return False, f"weights sum to {wsum:g} (expected 1 or 100)"
        norm = [w / wsum for w in weights]
        problems = []
        for c in alt_cols:
            if any(s is None for s in scores[c]) or totals.get(c) is None:
                problems.append(f"{header[c]}: missing score or total")
                continue
            calc = sum(w * s for w, s in zip(norm, scores[c]))
            stated = totals[c]
            # allow totals expressed on the weight scale (e.g. weights in %): stated may equal calc*wsum
            if not any(abs(stated - x) <= max(tol * abs(x), 0.011) for x in (calc, calc * wsum)):
                problems.append(f"{_strip_md(header[c])}: stated {stated:g} vs computed {calc:.3f}")
        if problems:
            return False, "; ".join(problems)
        return True, f"{len(weights)} criteria x {len(alt_cols)} alternatives recomputed; totals consistent"
    return False, "no decision matrix table with a 'Weight' column and a 'Weighted total' row"


