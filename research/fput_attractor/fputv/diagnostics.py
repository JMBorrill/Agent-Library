"""Diagnostics for stroboscopic (drive-period-sampled) trajectories.

Limitations, stated once here and repeated in the report:
* Stroboscopic sampling folds all frequencies into [0, 1) cycles per drive period.
* Rotation numbers from a planar projection are meaningful only if the projected curve
  winds monotonically about its centroid (checked: `monotone_fraction`).
* A finite-time Lyapunov exponent can only bound |lambda_1| from above at the level of its
  O(1/t) finite-time fluctuation; it cannot prove lambda_1 = 0.
* No finite simulation excludes an arbitrarily long transient; the tests below can only bound
  drift within the integrated window.
"""
from __future__ import annotations

import numpy as np
from scipy.optimize import minimize_scalar


def pca_plane(Y):
    X = Y - Y.mean(axis=0)
    _, s, Vt = np.linalg.svd(X, full_matrices=False)
    return X @ Vt[:2].T, s / s[0]


def rotation_number(Y):
    """Signed mean angle increment / 2 pi of the stroboscopic orbit in its PCA plane."""
    P, sv = pca_plane(Y)
    ang = np.unwrap(np.arctan2(P[:, 1], P[:, 0]))
    inc = np.diff(ang)
    rho = inc.mean() / (2 * np.pi)
    sgn = np.sign(rho) if rho != 0 else 1.0
    h = len(inc) // 2
    return {"rho": float(rho),
            "rho_first_half": float(inc[:h].mean() / (2 * np.pi)),
            "rho_second_half": float(inc[h:].mean() / (2 * np.pi)),
            "monotone_fraction": float(np.mean(sgn * inc > 0)),
            "modulation_period_drive_cycles": float(1 / abs(rho)) if rho else float("inf"),
            "pca_singular_value_ratios": [float(x) for x in sv[:6]]}


def refined_frequency(z, f0=None):
    """NAFF-style frequency of a (complex) series: maximise the Hann-windowed Fourier amplitude.

    Returns cycles per sample in (-0.5, 0.5]. For quasiperiodic signals the error decays much
    faster than the FFT bin width 1/n."""
    z = np.asarray(z, complex)
    z = z - z.mean()
    n = len(z)
    w = np.hanning(n)
    k = np.arange(n)
    if f0 is None:
        spec = np.abs(np.fft.fft(z * w))
        f0 = np.fft.fftfreq(n)[int(np.argmax(spec))]

    def neg_amp(f):
        return -abs(np.sum(w * z * np.exp(-2j * np.pi * f * k)))

    r = minimize_scalar(neg_amp, bounds=(f0 - 1.5 / n, f0 + 1.5 / n), method="bounded",
                        options={"xatol": 1e-14})
    return float(r.x)


def frequency_diffusion(Y, nwin=4):
    """Refined rotation frequency in consecutive windows (Laskar-type frequency map test)."""
    P, _ = pca_plane(Y)
    z = P[:, 0] + 1j * P[:, 1]
    L = len(z) // nwin
    fs = [refined_frequency(z[i * L:(i + 1) * L]) for i in range(nwin)]
    return {"window_frequencies": fs, "max_abs_drift": float(np.max(fs) - np.min(fs)),
            "window_length": L}


def line_spectrum(x, rho, kmax=40, top=25, guard=3):
    """Test whether the spectrum of a stroboscopic scalar series is a line spectrum generated by
    the single frequency rho (folded: |k rho mod 1| for |k| <= kmax).

    Returns the fraction of (Hann-windowed) power within +-guard bins of predicted lines and the
    mismatch of the strongest peaks from the nearest predicted line, in FFT bins."""
    x = np.asarray(x, float) - np.mean(x)
    n = len(x)
    S = np.abs(np.fft.rfft(x * np.hanning(n))) ** 2
    f = np.fft.rfftfreq(n)
    pred = np.abs(((np.arange(-kmax, kmax + 1) * rho + 0.5) % 1.0) - 0.5)
    pred_bins = np.round(pred * n).astype(int)
    mask = np.zeros(len(S), bool)
    for b in pred_bins:
        mask[max(0, b - guard): b + guard + 1] = True
    frac = float(S[mask].sum() / S.sum())
    # local maxima, strongest first
    lm = np.where((S[1:-1] > S[:-2]) & (S[1:-1] > S[2:]))[0] + 1
    lm = lm[np.argsort(-S[lm])][:top]
    mism = [float(np.min(np.abs(f[i] - pred)) * n) for i in lm]
    floor = float(np.median(S[~mask])) if (~mask).any() else 0.0
    return {"power_fraction_on_predicted_lines": frac,
            "top_peak_mismatch_bins_max": float(max(mism)),
            "top_peak_freqs": [float(f[i]) for i in lm[:10]],
            "dynamic_range_peak_over_offline_median": float(S.max() / floor) if floor > 0 else float("inf"),
            "n": n}


def invariant_circle_fit(Y, harmonics=(2, 5, 10, 20, 40, 80, 120)):
    """Least-squares fit y(theta) = sum_{|j|<=J} c_j e^{i j theta} of every state component as a
    function of the PCA angle theta. For a smooth invariant circle the RMS residual falls rapidly
    with J to the integration-noise level; for a 3-torus or chaotic set it saturates."""
    P, _ = pca_plane(Y)
    th = np.arctan2(P[:, 1], P[:, 0])
    Yc = Y - Y.mean(axis=0)
    scale = float(np.sqrt(np.mean(np.sum(Yc ** 2, axis=1))))
    out = {}
    for J in harmonics:
        cols = [np.ones_like(th)]
        for j in range(1, J + 1):
            cols += [np.cos(j * th), np.sin(j * th)]
        A = np.stack(cols, axis=1)
        coef, *_ = np.linalg.lstsq(A, Yc, rcond=None)
        res = Yc - A @ coef
        out[str(J)] = float(np.sqrt(np.mean(np.sum(res ** 2, axis=1))) / scale)
    return {"relative_rms_residual_by_harmonics": out, "attractor_rms_size": scale}


def recurrence_periods(Y, maxlag=500, tol=1e-6):
    """Smallest lag k with max_n |y_{n+k} - y_n| < tol over the window (exact periodicity test)."""
    best = []
    for k in range(1, min(maxlag, len(Y) - 1) + 1):
        d = float(np.max(np.abs(Y[k:] - Y[:-k])))
        best.append(d)
        if d < tol:
            return {"period": k, "max_return_distance": d, "min_over_lags": float(min(best))}
    return {"period": None, "min_over_lags": float(min(best)), "argmin_lag": int(np.argmin(best) + 1)}


def window_drift(E, nwin=5):
    """Mean/range of a scalar observable in consecutive windows (stationarity check)."""
    L = len(E) // nwin
    return {"window_means": [float(E[i * L:(i + 1) * L].mean()) for i in range(nwin)],
            "window_ranges": [float(np.ptp(E[i * L:(i + 1) * L])) for i in range(nwin)],
            "window_length": L}


def classify_state(Y, y_locked, sys, locked_tol=1e-4, modulated_range=1e-2):
    """Coarse label of the final window of a stroboscopic trajectory: 'locked' (converged to the
    given drive-locked fixed point), 'modulated' (E1 range above threshold), else 'undecided'."""
    d_end = float(np.max(np.abs(Y[-1] - y_locked)))
    E = sys.energies(Y)
    rng = float(np.ptp(E[:, 0]))
    if d_end < locked_tol and rng < modulated_range:
        lab = "locked"
    elif rng > modulated_range:
        lab = "modulated"
    else:
        lab = "undecided"
    return lab, d_end, rng
